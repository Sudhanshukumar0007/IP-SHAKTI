/**
 * Translate a key into the selected language.
 * Falls back to English if no translation exists.
 * Supports {placeholder} substitution.
 *
 * @param {string} key
 * @param {string} language
 * @param {Object} [vars]  — optional { placeholder: value } map
 * @returns {string}
 */
export function t(key, language, vars) {
  const entry = translations[key];

  if (!entry) {
    return key;
  }

  let text = entry[language] || entry.English || key;

  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, v);
    });
  }

  return text;
}
